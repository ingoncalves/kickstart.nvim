#Requires -Version 5.1

# link vim files and install plugins
$ErrorActionPreference = 'Stop'

$BaseDir = $PSScriptRoot
$ConfigDir = Join-Path $env:LOCALAPPDATA 'nvim'
New-Item -ItemType Directory -Force -Path $ConfigDir | Out-Null

$LoaderMarker = '-- Generated by kickstart.nvim install.ps1: loads the config from the repo'

function Test-LoaderStub($Item) {
  # true if the file is a loader written by this script (see New-ConfigLink)
  if ($Item.PSIsContainer) { return $false }
  $firstLine = Get-Content -LiteralPath $Item.FullName -TotalCount 1 -ErrorAction SilentlyContinue
  return $firstLine -eq $LoaderMarker
}

function New-ConfigLink {
  param(
    [string]$Source,
    [string]$Target
  )

  $existing = Get-Item -LiteralPath $Target -Force -ErrorAction SilentlyContinue
  if ($existing) {
    if ($existing.LinkType -or (Test-LoaderStub $existing)) {
      # existing link (symlink, junction or hardlink) or loader stub: replace it
      $existing.Delete()
    } else {
      # real file/dir: back it up instead of deleting it
      $backup = "$Target.bak"
      Write-Warning "$Target already exists, moving it to $backup"
      Move-Item -LiteralPath $Target -Destination $backup -Force
    }
  }

  $isDir = Test-Path -LiteralPath $Source -PathType Container
  try {
    # symlinks need admin rights or Developer Mode enabled
    New-Item -ItemType SymbolicLink -Path $Target -Target $Source | Out-Null
  } catch {
    # fall back to options that don't need elevation
    if ($isDir) {
      New-Item -ItemType Junction -Path $Target -Target $Source | Out-Null
    } else {
      # Not a hard link: those silently break when git or an editor saves the file by replacing it.
      # Write a tiny Lua file that loads the source instead.
      $luaPath = $Source -replace '\\', '/'
      $stub = "$LoaderMarker`ndofile([[$luaPath]])`n"
      [System.IO.File]::WriteAllText($Target, $stub) # UTF-8 without BOM
      Write-Host "Created loader $Target -> $Source"
      return
    }
  }
  Write-Host "Linked $Target -> $Source"
}

New-ConfigLink -Source (Join-Path $BaseDir 'init.lua') -Target (Join-Path $ConfigDir 'init.lua')
New-ConfigLink -Source (Join-Path $BaseDir 'lua') -Target (Join-Path $ConfigDir 'lua')
